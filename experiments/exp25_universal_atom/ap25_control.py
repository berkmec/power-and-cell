"""Exp25b (all neighbours): can the central atom control ALL of its coupled neighbours, including those that a selective RF
pulse cannot pick out of a crowded spectrum? Universal quantum interface (Lloyd, Landahl, Slotine 2004): with global controls
(electron ESR x/y, one nuclear RF x/y acting on every nucleus) and the drift H0 = sum_k S_z (A_k I_z^k) (secular hyperfine,
rotating frame), the generated Lie algebra is the full su(d) when all couplings are distinct and non-zero.
Couplings: Kohn-Luttinger contact part (exp25 calibration) + secular dipolar part T_k (3 cos^2 theta_k - 1),
T_k = (mu0/4pi) g_e mu_B |gamma_n| / r_k^3 (point dipole), B along [001]; the dipolar part separates symmetry-equivalent sites.
Tests: (1) Lie rank for natural-Si clusters (N = 3, 4 strongest neighbours) and for an exactly degenerate pair;
(2) GRAPE (piecewise-constant, L-BFGS-B, bounded amplitudes): CNOT(electron -> nucleus 1) for two nuclei 1 kHz apart (not
addressable by a 10 kHz-selective pulse); GHZ preparation over the electron and all 3 nuclei of a crowded cluster.
usage: python ap25_control.py  ->  results/exp25/control.json (predictions_control.json written first)"""
import json
