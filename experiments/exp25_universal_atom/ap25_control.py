OUT = Path(__file__).resolve().parents[2] / "results" / "exp25"
TWO_PI = 2 * np.pi
sx = np.array([[0, 1], [1, 0]], complex) / 2
sy = np.array([[0, -1j], [1j, 0]], complex) / 2
sz = np.array([[1, 0], [0, -1]], complex) / 2
I2 = np.eye(2, dtype=complex)


def op(single, pos, n):
    out = np.array([[1.0 + 0j]])
    for k in range(n):
        out = np.kron(out, single if k == pos else I2)
    return out


def operators(N):
    n = N + 1
    Se = [op(s, 0, n) for s in (sx, sy, sz)]
    In = [[op(s, k + 1, n) for s in (sx, sy, sz)] for k in range(N)]
    return Se, In


def drift(A_mhz, Se, In):
    return sum(TWO_PI * a * Se[2] @ In[k][2] for k, a in enumerate(A_mhz))


def controls(Se, In, N):
    return [Se[0], Se[1], sum(In[k][0] for k in range(N)), sum(In[k][1] for k in range(N))]


def lie_rank(gens, max_dim=None):
    """dimension of the real Lie algebra generated by i*H (orthonormal basis, iterative commutators)"""
    d = gens[0].shape[0]
    max_dim = max_dim or d * d - 1
    basis = []

    def add(M):
        v = np.concatenate([M.real.ravel(), M.imag.ravel()])
        for b in basis:
            v = v - (b @ v) * b
        nv = np.linalg.norm(v)
        if nv > 1e-8:
            basis.append(v / nv)
            return True
        return False

    def mat(v):
        h = d * d
        return (v[:h] + 1j * v[h:]).reshape(d, d)

    frontier = []
    for g in gens:
        M = 1j * g
        M = M - np.trace(M) / d * np.eye(d)
        if add(M):
            frontier.append(M)
    while frontier and len(basis) < max_dim:
        new = []
        for M in frontier:
            for g in gens:
                C = M @ (1j * g) - (1j * g) @ M
                if np.linalg.norm(C) > 1e-9 and add(C):
                    new.append(mat(basis[-1]))
                if len(basis) >= max_dim:
                    break
            if len(basis) >= max_dim:
                break
        frontier = new
    return len(basis), max_dim


def couplings(pts, A_iso):
    mu0_4pi, ge_mub, gn = 1e-7, 2.0023 * 9.2740100783e-24, 8.465e6
    r = np.linalg.norm(pts, axis=1) * 1e-9
    cos = pts[:, 2] / np.linalg.norm(pts, axis=1)
    T = mu0_4pi * ge_mub * gn / r**3                      # Hz
    return A_iso + T * (3 * cos**2 - 1), T


def grape(H0, Hc, target, T_us, M, umax, state=None, iters=400, seed=0):
    d = H0.shape[0]
    dt = T_us / M
    rng = np.random.default_rng(seed)
    x0 = (rng.random(len(Hc) * M) - 0.5) * 0.2 * np.repeat(umax, M)
    bounds = [(-u, u) for u in umax for _ in range(M)]

    def fid_grad(x):
        """exact gradient: dU_j/du_kj from the Frechet derivative of expm (dt*|H| is large here, ~40 rad per slice)"""
        u = x.reshape(len(Hc), M)
        Us, dUs = [], []
        for j in range(M):
            Aj = -1j * dt * (H0 + sum(u[k, j] * Hc[k] for k in range(len(Hc))))
            Uj, dj = None, []
            for k in range(len(Hc)):
                Uk, dk = expm_frechet(Aj, -1j * dt * Hc[k])
                Uj = Uk
                dj.append(dk)
            Us.append(Uj)
            dUs.append(dj)
        if state is None:
            X = [np.eye(d, dtype=complex)]
            for U in Us:
                X.append(U @ X[-1])                           # X[j] = U_j ... U_1 (slices 0..j-1)
            P = [target.conj().T]
            for U in reversed(Us):
                P.append(P[-1] @ U)
            P = P[::-1]                                       # P[j] = target^dag U_M ... U_{j+1}
            phi = np.trace(target.conj().T @ X[M])
            F = abs(phi) ** 2 / d**2
            g = np.zeros_like(u)
            for j in range(M):
                for k in range(len(Hc)):
                    dphi = np.trace(P[j + 1] @ dUs[j][k] @ X[j])
                    g[k, j] = 2 * np.real(np.conj(phi) * dphi) / d**2
        else:
            psi = [state[0]]
            for U in Us:
                psi.append(U @ psi[-1])
            lam = [state[1]]
            for U in reversed(Us):
                lam.append(U.conj().T @ lam[-1])
            lam = lam[::-1]                                   # lam[j] = U_{j+1}^dag ... U_M^dag |target>
            phi = np.vdot(state[1], psi[M])
            F = abs(phi) ** 2
            g = np.zeros_like(u)
            for j in range(M):
                for k in range(len(Hc)):
                    dphi = np.vdot(lam[j + 1], dUs[j][k] @ psi[j])
                    g[k, j] = 2 * np.real(np.conj(phi) * dphi)
        return -F, -g.ravel()

    res = minimize(fid_grad, x0, jac=True, method="L-BFGS-B", bounds=bounds, options=dict(maxiter=iters))
    return -res.fun, res.nit


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    pf = OUT / "predictions_control.json"
    if not pf.exists():
        pf.write_text(json.dumps(dict(registered=time.strftime("%Y-%m-%d %H:%M"), predictions=[
            "CT1: for 10 random natural-Si clusters (N = 3 and N = 4 strongest neighbours, contact + secular dipolar couplings, "
            "B along [001]) the Lie algebra of drift + global controls is full su(d) in every cluster",
            "CT2: an exactly degenerate pair (isotropic only, equal couplings) gives a rank-deficient algebra; adding the "
            "secular dipolar part of two symmetry-equivalent sites with different orientation restores the full rank",
            "CT3: GRAPE reaches fidelity >= 0.99 for CNOT(electron -> nucleus 1) with A1 - A2 = 1 kHz within T = 4 ms "
            "(electron Rabi <= 1 MHz, global nuclear Rabi <= 10 kHz)",
            "CT4: GRAPE prepares the GHZ state of the electron and all 3 nuclei of a crowded cluster (two of them 1 kHz apart) "
            "with fidelity >= 0.99 within T = 4 ms"]), indent=1), encoding="utf-8")
    out = dict(rank={}, grape={})
    rng = np.random.default_rng(31)
    for N in (3, 4):
        Se, In = operators(N)
        full = []
        for c in range(10):
            occ = rng.random(len(reg.SITES)) < reg.ABUND
            pts, Aiso = reg.SITES[occ], reg.A_SITES[occ]
            A, _ = couplings(pts, Aiso)
            idx = np.argsort(-np.abs(A))[:N]
            H0 = drift(A[idx] / 1e6, Se, In)
            rk, mx = lie_rank([H0] + controls(Se, In, N))
            full.append(dict(rank=rk, full=mx, couplings_kHz=(A[idx] / 1e3).round(2).tolist()))
            print(f"N={N} cluster {c}: rank {rk}/{mx} couplings {full[-1]['couplings_kHz']}", flush=True)
        out["rank"][f"N={N}"] = full
    Se, In = operators(2)
    deg = drift([0.3, 0.3], Se, In)
    rk_deg, mx = lie_rank([deg] + controls(Se, In, 2))
    p1, p2 = np.array([[0.0, 0.0, reg.A0_NM]]), np.array([[reg.A0_NM, 0.0, 0.0]])          # equivalent [100] sites
    A1, _ = couplings(p1, np.array([2.981e6]))
    A2, _ = couplings(p2, np.array([2.981e6]))
    rk_dip, _ = lie_rank([drift([A1[0] / 1e6, A2[0] / 1e6], Se, In)] + controls(Se, In, 2))
    out["rank"]["degenerate_isotropic"] = dict(rank=rk_deg, full=mx)
    out["rank"]["equivalent_sites_with_dipolar"] = dict(rank=rk_dip, full=mx, A_kHz=[A1[0] / 1e3, A2[0] / 1e3])
    print("degenerate isotropic pair:", rk_deg, "/", mx, "| equivalent [100] sites with dipolar:", rk_dip, "/", mx,
          [round(A1[0] / 1e3, 1), round(A2[0] / 1e3, 1)], flush=True)
    umax = np.array([TWO_PI * 1.0, TWO_PI * 1.0, TWO_PI * 0.01, TWO_PI * 0.01])      # rad/us
    H0 = drift([0.300, 0.301], Se, In)
    Hc = controls(Se, In, 2)
    P0, P1 = np.diag([1, 0]).astype(complex), np.diag([0, 1]).astype(complex)
    X = np.array([[0, 1], [1, 0]], complex)
    target = np.kron(np.kron(P0, X), I2) + np.kron(np.kron(P1, I2), I2)
    best = 0.0
    for seed in range(3):
        F, nit = grape(H0, Hc, target, 4000.0, 200, umax, seed=seed)
        best = max(best, F)
        print(f"GRAPE CNOT(e -> n1), A = 300/301 kHz, T = 4 ms, seed {seed}: F = {F:.4f} ({nit} it)", flush=True)
    out["grape"]["CNOT_1kHz_pair"] = dict(best_fidelity=best, T_ms=4.0, slices=200)
    Se3, In3 = operators(3)
    H03 = drift([0.300, 0.301, 0.180], Se3, In3)
    Hc3 = controls(Se3, In3, 3)
    psi0 = np.zeros(16, complex)
    psi0[0] = 1.0
    ghz = np.zeros(16, complex)
    ghz[0] = ghz[15] = 1 / np.sqrt(2)
    bestg = 0.0
    for seed in range(3):
        F, nit = grape(H03, Hc3, None, 4000.0, 200, umax, state=(psi0, ghz), seed=seed)
        bestg = max(bestg, F)
        print(f"GRAPE GHZ(e + 3 nuclei), A = 300/301/180 kHz, T = 4 ms, seed {seed}: F = {F:.4f} ({nit} it)", flush=True)
    out["grape"]["GHZ_3_nuclei_crowded"] = dict(best_fidelity=bestg, T_ms=4.0, slices=200)
    (OUT / "control.json").write_text(json.dumps(out, indent=1), encoding="utf-8")


def couplings_dir(pts, A_iso, bdir):
    mu0_4pi, ge_mub, gn = 1e-7, 2.0023 * 9.2740100783e-24, 8.465e6
    rn = np.linalg.norm(pts, axis=1)
    cos = pts @ bdir / rn
    return A_iso + mu0_4pi * ge_mub * gn / (rn * 1e-9) ** 3 * (3 * cos**2 - 1)


