def universal_all():
    """(1) general-N mechanism: ad_{H0}^{2j}(sum_k I_x^k) = (1/4)^j sum_k A_k^{2j} I_x^k (Vandermonde); distinct non-zero A_k
    make every single-nucleus I_x^k a linear combination of these global commutators -> each neighbour individually
    controllable, for any N. Checked with full matrices for N = 6, 8, 10 (d up to 2048) and a degenerate control case.
    (2) time to resolve ALL 29Si within 6 nm, T = 1 / min(min gap, min coupling), against the measured T2e of P donors in 28Si
    (2 s, Tyryshkin et al. Nature Mater. 2012)."""
    pf = OUT / "predictions_control3.json"
    if not pf.exists():
        pf.write_text(json.dumps(dict(registered=time.strftime("%Y-%m-%d %H:%M"), predictions=[
            "UN1: for N = 6, 8, 10 strongest neighbours (natural Si, B || [1,2,3]) the even nested commutators of the global RF "
            "with the hyperfine drift span N independent directions and reconstruct I_x of nucleus 1 with relative error < 1e-6; "
            "with A_1 = A_2 forced the rank drops to N - 1 and the error is > 0.1",
            "UN2: at 0.1 % 29Si, in >= 80 % of configurations the time to resolve all 29Si within 6 nm is < 0.2 s (T2e / 10, "
            "T2e = 2 s measured in 28Si)",
            "UN3: in natural Si the same time exceeds 1 s in >= 90 % of configurations"]), indent=1), encoding="utf-8")
    out = dict(vandermonde={}, times={})
    bdir = np.array([1.0, 2.0, 3.0]) / np.sqrt(14)
    rng = np.random.default_rng(4242)
    occ = rng.random(len(reg.SITES)) < reg.ABUND
    pts, Aiso = reg.SITES[occ], reg.A_SITES[occ]
    A_all = couplings_dir(pts, Aiso, bdir)
    order = np.argsort(-np.abs(A_all))
    for N, degenerate in ((6, False), (8, False), (10, False), (6, True)):
        A = A_all[order[:N]] / np.max(np.abs(A_all[order[:N]]))       # scaled: the Lie algebra does not depend on units
        if degenerate:
            A = A.copy()
            A[1] = A[0]
        Se, In = operators(N)
        H0 = sum(a * Se[2] @ In[k][2] for k, a in enumerate(A))
        O = sum(In[k][0] for k in range(N))
        vecs = []
        cur = O
        for j in range(N):
            vecs.append(cur.ravel())
            cur = H0 @ cur - cur @ H0
            cur = H0 @ cur - cur @ H0                                   # two commutators: ad^2 brings A_k^2
        V = np.array(vecs).T
        s = np.linalg.svd(V, compute_uv=False)
        rank = int(np.sum(s > s[0] * 1e-12))
        target = In[0][0].ravel()
        w, *_ = np.linalg.lstsq(V, target, rcond=1e-14)
        err = float(np.linalg.norm(V @ w - target) / np.linalg.norm(target))
        key = f"N={N}{', A1=A2' if degenerate else ''}"
        out["vandermonde"][key] = dict(rank=rank, N=N, rel_error=err, smallest_sv_ratio=float(s[-1] / s[0]),
                                       couplings_scaled=np.round(A, 5).tolist())
        print(f"{key}: rank {rank}/{N}, reconstruction error of I_x(1) {err:.2e}, sv ratio {s[-1]/s[0]:.2e}", flush=True)
    for label, ab in (("natural 4.685 %", 0.04685), ("0.1 %", 0.001), ("50 ppm", 5e-5)):
        T, n_list = [], []
        for c in range(100):
            occ = rng.random(len(reg.SITES)) < ab
            if occ.sum() == 0:
                T.append(0.0)
                n_list.append(0)
                continue
            A = np.abs(couplings_dir(reg.SITES[occ], reg.A_SITES[occ], bdir))
            srt = np.sort(A)
            gap = np.min(np.diff(srt)) if len(srt) > 1 else np.inf
            res = min(gap, srt[0])
            T.append(float(1.0 / res) if res > 0 else np.inf)
            n_list.append(int(occ.sum()))
        T = np.array(T)
        out["times"][label] = dict(n_29Si_within_6nm=float(np.mean(n_list)), median_T_s=float(np.median(T)),
                                   frac_below_0p2s=float(np.mean(T < 0.2)), frac_above_1s=float(np.mean(T > 1.0)),
                                   frac_exact_degenerate=float(np.mean(~np.isfinite(T))))
        print(label, out["times"][label], flush=True)
    (OUT / "control_all.json").write_text(json.dumps(out, indent=1), encoding="utf-8")


